-- Messages éclair entre transporteur et admin (demande d'Aly, 2026-11-16).
-- Canal libre/texte, distinct de transporteur_notifications (événements
-- système à sens unique : nouvelle mission, incident...) : ici, un
-- transporteur et l'admin peuvent s'écrire librement, dans les deux sens.
-- `lu` = lu par le DESTINATAIRE (celui qui n'a pas écrit le message).
create table if not exists messages_transporteur (
  id bigint generated by default as identity primary key,
  transporteur_id bigint not null references transporteurs(id) on delete cascade,
  expediteur text not null check (expediteur in ('transporteur','admin')),
  contenu text not null,
  lu boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists idx_messages_transporteur_tid_date on messages_transporteur(transporteur_id, created_at desc);
